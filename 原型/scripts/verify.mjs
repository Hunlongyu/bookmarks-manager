async function pageAt(width = 1440, height = 900) {
  const p = await browser.newPage({ viewport: { width, height }, deviceScaleFactor: 1, reducedMotion: 'reduce', acceptDownloads: true });
  p.setDefaultTimeout(7000);
  p.on('pageerror', e => errors.push(e.message));
  p.on('request', req => { if (/^https?:/.test(req.url())) externalRequests.push(req.url()); });
  p.on('dialog', d => d.accept());
  await p.goto(pathToFileURL(resolve(root, '原型/index.html')).href);
  return p;
}
